# Filter on the interpretation (same categories as _reading, the local FoldDisco).
_FILTERS = {
    "Same motif (strong) only": {"same motif (strong)"},
    "Same motif + shared (broad/partial)": {
        "same motif (strong)",
        "residues largely shared, loose superposition",
        "partially shared motif"},
    "All": None,
}
