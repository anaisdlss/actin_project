def folddisco_pair_map(abps):
    """Returns {frozenset({A,B}): {FoldDisco columns}} for the given ABPs.

    None if FoldDisco not computed; {} if no pair. All values come from
    a SINGLE hit (the smaller motif searched in the other), so they are consistent.
    Columns = raw `folddisco query` outputs + normalised versions:
      * 'Matched residues' = n_match / size of the queried motif (raw)
      * '% shared motif'   = n_match / size (coverage, %)
      * 'FoldDisco score'  = raw score (rarity, no absolute scale)
      * 'Norm. score'      = score / self-match (a ratio, not a calibrated quality)
      * 'RMSD (Å)'         = superposition of matched residues (low = true
                             3D overlap; note: trivially low if few residues).
    """
    mt = os.path.getmtime(_FD_CSV) if os.path.exists(_FD_CSV) else 0.0
    df = _load_folddisco(mt)
    if df is None:
        return None
    aset = set(abps)
    sub = df[df["query_abp"].isin(aset) & df["target_abp"].isin(aset)
             & (~df["self"])].copy()
    if sub.empty:
        return {}
    # ACTUAL motif size of each ABP = number of contact residues (query_size)
    qsize = (df.drop_duplicates("query_abp")
             .set_index("query_abp")["query_size"].to_dict())
    sub["pair"] = sub.apply(
        lambda r: frozenset((r["query_abp"], r["target_abp"])), axis=1)
    out = {}
    for pair, g in sub.groupby("pair"):
        a, b = sorted(pair)
        # ONE direction of comparison so the 4 columns are consistent:
        # "is the SMALLER of the two motifs found in the other?" (the most
        # stringent). All values come from THIS hit — score, score_norm,
        # coverage and RMSD describe the same match.
        sa, sb = qsize.get(a), qsize.get(b)
        small = a if (sa or 1e9) <= (sb or 1e9) else b
        rsmall = g[g["query_abp"] == small]
        _hit = rsmall.iloc[0] if len(rsmall) else g.loc[g["score"].idxmax()]
        _qsz = qsize.get(_hit["query_abp"])
        n_used = int(_hit["n_match"])
        frac = n_used / _qsz if _qsz else None
        sn = pd.to_numeric(_hit.get("score_norm"), errors="coerce")
        _rmsd = pd.to_numeric(_hit.get("rmsd"), errors="coerce")
        _snv = float(sn) if pd.notna(sn) else None
        _rmv = float(_rmsd) if pd.notna(_rmsd) else None
        out[pair] = {
            # raw FoldDisco outputs (query -> target) + normalised versions
            "Matched residues": (f"{n_used}/{_qsz}" if _qsz else str(n_used)),  # n_match
            "% shared motif": (f"{round(frac * 100)}%" if frac is not None else "—"),
            "FoldDisco score": round(float(_hit["score"]), 1),                  # score brut
            "Norm. score": round(_snv, 2) if _snv is not None else None,        # score/self
            "RMSD (Å)": round(_rmv, 1) if _rmv is not None else None,           # rmsd
            "Interpretation": _reading(n_used, frac, _snv, _rmv),
        }
    return out


