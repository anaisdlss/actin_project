# No binary "same motif" verdict: the raw FoldDisco score has no absolute scale
# and no threshold cleanly separates the distributions (strong overlap between
# same-family / different-family). So we expose the values and let the reader
# judge: score_norm (a source-relative ratio) + % shared motif (coverage).


def _reading(n_used, frac, sn, rmsd):
    """GRADED reading (a guide, not a verdict) combining the 4 FoldDisco signals:
    coverage (frac), geometric quality (score_norm), fidelity (RMSD) and
    number of residues (robustness). A low RMSD on few residues is not
    conclusive; high coverage with high RMSD = shared but loose."""
    if n_used is None or frac is None or pd.isna(n_used) or pd.isna(frac):
        return "missing metrics — unclassified"
    if n_used < 5:
        return "few residues — inconclusive"
    _tight = rmsd is not None and rmsd <= 4          # tight superposition
    _loose = rmsd is not None and rmsd > 6           # loose superposition
    if frac >= 0.75 and _tight and (sn or 0) >= 0.15:
        return "same motif (strong)"
    if frac >= 0.75:                                 # well covered but not tight
        return "residues largely shared, loose superposition"
    if frac >= 0.50:
        return "partially shared motif"
    return "different motifs"


